/**
 * Тонкая кишка: петли внутри рамки толстой.
 * Прежняя спираль читалась пружиной именно потому, что была одной винтовой
 * линией с постоянным радиусом — здесь ход змейкой с переменной амплитудой.
 */
export function buildSmallIntestine() {
    const controls = [];
    const steps = 26;
    for (let i = 0; i <= steps; i += 1) {
        const t = i / steps;
        const amplitude = 0.20 - 0.055 * Math.cos(t * Math.PI * 3);
        controls.push({
            x: Math.sin(t * Math.PI * 7.5) * amplitude,
            y: 0.17 - t * 0.52,
            z: 0.06 + Math.cos(t * Math.PI * 5) * 0.045,
            rx: 0.038,
            rz: 0.038,
        });
    }
    return sweepProfile(controls, 150, 14);
}

