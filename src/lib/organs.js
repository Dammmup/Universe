/**
 * Геометрия внутренних органов.
 *
 * Прежние органы были набором примитивов: лёгкие — двумя шарами, кишечник —
 * буквальной пружиной, мозг — двумя сферами. Здесь каждый орган собран той же
 * протяжкой сечений, что и фигура: форма задаётся профилем радиусов вдоль
 * осевой линии, поэтому сердце сужается к верхушке, доля лёгкого — конус с
 * куполом, а кишка идёт петлями, а не витками.
 *
 * Все органы строятся вокруг локального нуля, а ставятся на место позицией
 * меша: шейдер ткани (`tissueVertex`) считает складки по локальным координатам
 * вершины, и в координатах фигуры борозды коры выродились бы в рябь.
 */

/** Сердце: конус с закруглённым основанием, верхушка смотрит вниз-влево-вперёд. */
export function buildHeart() {
    return sweepProfile([
        { x: 0.00, y: 0.21, z: -0.01, rx: 0.03, rz: 0.03 },
        { x: -0.01, y: 0.16, z: -0.01, rx: 0.15, rz: 0.13 },  // основание, предсердия
        { x: -0.02, y: 0.08, z: 0.00, rx: 0.19, rz: 0.16 },
        { x: -0.04, y: -0.01, z: 0.01, rx: 0.19, rz: 0.16 },  // желудочки
        { x: -0.07, y: -0.09, z: 0.03, rx: 0.15, rz: 0.13 },
        { x: -0.10, y: -0.17, z: 0.05, rx: 0.09, rz: 0.08 },
        { x: -0.12, y: -0.23, z: 0.06, rx: 0.01, rz: 0.01 },  // верхушка
    ], 70, 26);
}

/**
 * Доля лёгкого: купол сверху, широкое основание на диафрагме.
 * `notch` поджимает левую долю — там, где в грудной клетке лежит сердце.
 */
export function buildLung(notch = 0) {
    const w = 1 - notch * 0.16;
    return sweepProfile([
        // Купол не сводится в иглу: анатомически верхушка узкая, но на просвет
        // тонкий конус пропадал совсем, и лёгкое выглядело обрезанным сверху
        { y: 0.44, z: -0.02, rx: 0.03, rz: 0.03 },
        { y: 0.38, z: -0.01, rx: 0.12 * w, rz: 0.11 },   // купол
        { y: 0.24, z: 0.00, rx: 0.19 * w, rz: 0.17 },
        { y: 0.06, z: 0.01, rx: 0.23 * w, rz: 0.20 },
        { y: -0.12, z: 0.01, rx: 0.24 * w, rz: 0.20 },
        { y: -0.28, z: 0.00, rx: 0.21 * w, rz: 0.17 },
        { y: -0.40, z: -0.01, rx: 0.12 * w, rz: 0.10 },  // основание на диафрагме
        { y: -0.45, z: -0.01, rx: 0.02, rz: 0.02 },
    ], 80, 26);
}

