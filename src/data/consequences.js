/** Действует ли обратное состояние фактора: сам перевёрнут или пришло эхо. */
export function isEffectivelyReversed(reversed, id) {
    if (reversed[id]) return true;
    return LINKS.some((l) => l.to === id && reversed[l.from]);
}

/** Какие источники сейчас шлют эхо в этот фактор. */
export const activeSourcesOf = (reversed, id) => LINKS.filter((l) => l.to === id && reversed[l.from]);

/** Куда уходит эхо от фактора. */
export const echoesOf = (id) => LINKS.filter((l) => l.from === id);

/**
 * Состояние всех факторов для картинки: к перевёрнутым добавлены цели эха.
 * Для сцен, которые читают весь словарь разом (глобус, тело).
 */
export function withEchoes(reversed) {
    const out = { ...reversed };
    LINKS.forEach((l) => {
        if (reversed[l.from]) out[l.to] = true;
    });
    return out;
}
