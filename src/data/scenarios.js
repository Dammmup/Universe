export const scenarioById = (id) => SCENARIOS.find((s) => s.id === id) ?? null;

/**
 * Какие сценарии сложились и ещё не были показаны. Крупные комбинации идут
 * первыми: если одним переключением собраны «Мир без войн» и «Утопия»,
 * зритель сначала видит более полную картину.
 */
export function newlyCompleted(reversed, discovered) {
    return SCENARIOS
        .filter((s) => !discovered[s.id] && s.factors.every((f) => reversed[f]))
        .sort((a, b) => b.factors.length - a.factors.length)
        .map((s) => s.id);
}
